class PlaceholderGadget(Gadget):
    """A gadget that acts as a placeholder for some other gadgets."""

    def __init__(self, label: str | bytes = b""):
        """Initialize a placeholder gadget.

        Args:
            label: The label of the placeholder; default b"".
        """
        super().__init__()
        if isinstance(label, str):
            label = label.encode()
        self.placeholder_label: bytes = label

    def __bytes__(self) -> bytes:
        return self.placeholder_label

    def sanity_check(self) -> bool:
        return False


class NullGadget(Gadget):
    """An empty gadget."""

    def __bytes__(self) -> bytes:
        return b""


class CustomOrRandomGadget(Gadget):
    """A gadget that can be constructed in two ways, either with its content
    provided on initialization or constructed as a random byte string."""

    def __init__(
        self,
        content: bytes | None = None,
        length: int | None = None,
        charset: bytes | None = None,
    ):
        super().__init__()
        self.content: bytes | None = content
        self.length: int | None = length if content is None else len(content)
        self.charset: bytes | None = charset

    def get_length(self) -> int:
        """Get or compute the length of the gadget. Override this method
        to allow determining the length of the gadget on compile time."""
        return 0 if self.length is None else self.length

    def __call__(self, rng: Random | None) -> bytes | None:
        if self.content is not None:
            return self.content
        charset = charset_with_fallback(self.charset, self.machine)
        return RandBytes(charset, rng).randbytes(self.get_length())


class ParallelGadget(Gadget):
    """A gadget composed of several different gadgets in parallel, which
    resolves to one of the constituent gadgets on compilation.

    A `ParallelGadget` can be used to automatically select on compile time
    which gadget to use among several gadgets with the same functionality but
    designed for different DEFLATE parameters.
    """

    def __init__(
        self,
        gadgets: Sequence[Gadget],
        resolver: Callable[["ParallelGadget"], Gadget | None] | None = None,
    ):
        """Initialize a parallel gadget.

        Args:
            gadgets: A sequence of gadgets; if `resolver` (see below) is not
                provided or is `None`, then the gadgets closer to the front of
                the sequence have higher priorities.
            resolver: An optional custom-defined function that selects one of
                the gadgets to use on compile time. Default `None`.
        """
        assert len(gadgets) > 0
        self.gadgets = gadgets
        self.resolver = resolver
        self.gadget_in_use: Gadget | None = None
        super().__init__()

    def resolve(self) -> Gadget | None:
        if self.resolver is not None:
            return self.resolver(self)
        for gadget in self.gadgets:
            if gadget.sanity_check():
                return gadget
        return None

    def set_prev_gadget(self, gadget: "Gadget | None") -> None:
        super().set_prev_gadget(gadget)
        for sub_gadget in self.gadgets:
            sub_gadget.set_prev_gadget(gadget)

    def bind(self, machine: "CRIMEAutomaton | None", should_flush: bool = True) -> None:
        super().bind(machine, should_flush=should_flush)

        for gadget in self.gadgets:
            gadget.bind(machine=machine, should_flush=True)

    def __call__(self, rng: Random | None) -> bytes | None:
        self.gadget_in_use = cur_gadget = self.resolve()
        if cur_gadget is None:
            return None

        output = cur_gadget.compile(rng, force_recompile=True, execute_actions=False)
        self.actions = cur_gadget.actions
        return output

    def sanity_check(self) -> bool:
        for gadget in self.gadgets:
            if gadget.sanity_check():
                return True
        return False


class SeriesGadget(Gadget):
    """A gadget composed of several gadgets connected in series."""

    def __init__(
        self,
        gadgets: Iterable[Gadget],
    ):
        """Initialize a series gadget.

        Args:
            gadgets: A sequence of gadgets. The constructed `SeriesGadget`
                keeps the order of the gadgets in `gadgets`.
        """
        super().__init__()
        self.gadgets = [gadget for gadget in gadgets]
        assert len(self.gadgets) > 0

    def set_prev_gadget(self, gadget: "Gadget | None") -> None:
        super().set_prev_gadget(gadget)
        self.gadgets[0].set_prev_gadget(gadget)

    def bind(self, machine: "CRIMEAutomaton | None", should_flush: bool = True) -> None:
        super().bind(machine, should_flush=should_flush)

        for gadget in self.gadgets:
            gadget.bind(machine=machine, should_flush=True)

    def __call__(self, rng: Random | None) -> bytes | None:
        """We use a hack in this method to make it portable as a pre-compiled
        gadget. This should work but not quite efficient as you can see."""
        cached_gadgets: list[PrecompiledGadget] = []
        for gadget in self.gadgets:
            pc_gadget = gadget.derive_precompiled_gadget(force_recompile=True)
            if pc_gadget is None:
                return None
            cached_gadgets.append(pc_gadget)

        output = b""

        def align_prev_gadget(gadget: Gadget) -> None:
            cached_gadgets[0].set_prev_gadget(gadget)

        self.actions = [align_prev_gadget]

        for pc_gadget in cached_gadgets:
            output += pc_gadget.compiled_output
            for action in pc_gadget.compiled_actions:
                if action:
                    self.actions.append(lambda _: action(pc_gadget))

        return output

    def sanity_check(self) -> bool:
        for gadget in self.gadgets:
            if not gadget.sanity_check():
                return False
        return True


class MirrorGadget(Gadget):
    """
    A gadget that always produces the same output (and actions) as a previous
    gadget in the automaton, unless it is frozen (not recommended).

    Note that we assume the mirror gadget is in the same automaton as the
    gadget being mirrored and the mirror gadget has a higher index in the
    sequence of gadgets, which allows it to always be compiled after the
    mirrored gadget; otherwise, this gadget may not function correctly.
    """

    def __init__(self, model_gadget: Gadget, ignore_actions: bool = False):
        """Initialize a mirror gadget.

        Args:
            model_gadget: The gadget being mirrored, which is supposed to be
                in the same automaton and precede the current gadget.
            ignore_actions: If set to `True`, the gadget will not copy the
                actions of the mirrored gadget on compilation. Default `False`.
        """
        super().__init__()
        self.model_gadget = model_gadget
        self.ignore_actions = ignore_actions

    def sanity_check(self) -> bool:
        return self.model_gadget.sanity_check()

    def __call__(self, rng: Random | None) -> bytes | None:
        output = self.model_gadget.output
        if not self.ignore_actions:
            self.actions = self.model_gadget.actions
        return output

    def compile(
        self, rng: Random | None, force_recompile: bool, execute_actions: bool
    ) -> bytes | None:
        """We override the `compile` method to always force to recompile."""
        return super().compile(rng, True, execute_actions)
