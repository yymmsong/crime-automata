class Gadget(Compilable):
    def __init__(self, machine: "CRIMEAutomaton | None" = None):
        self.prev_gadget: Gadget | None = None
        # Not really `Any` but `Self`, just too tired to care about types
        self.actions: list[Callable[[Any], None] | None] = []
        super().__init__(machine=machine)

    def _last_bytes(self, length: int, strict: bool = True) -> bytes:
        """Fetch the last `length` bytes of output from the gadgets preceding
        the current gadget. If `strict=False`, then at most `length`
        bytes are returned.
        """
        assert length >= 0
        if length == 0:
            return b""
        if self.prev_gadget is None:
            assert not strict
            return b""
        prev_output = self.prev_gadget.output
        if prev_output is None:
            assert not strict
            return b""

        prev_len = len(prev_output)
        if prev_len >= length:
            return prev_output[-length:]
        else:
            return self.prev_gadget._last_bytes(length - prev_len, strict) + prev_output

    @staticmethod
    def compound_word(pref_len: int, rest: bytes) -> Callable[["Gadget"], bytes]:
        """Return a closure that on call with an argument `gadget` returns a
        byte string generated by concatenating the last `pref_len` bytes before
        `gadget` in the output of the automaton and a byte string `rest`."""
        return lambda gadget: gadget._last_bytes(pref_len, strict=True) + rest

    def derive_precompiled_gadget(
        self, rng: Random | None = None, force_recompile: bool = False
    ) -> "PrecompiledGadget | None":
        """Derive a precompiled gadget from the current gadget.

        Again, one should be very careful when invoking this method for some
        gadget that on compilation spawns actions which in turn uses some
        attributes or methods of the gadget; the current solution is to rebind
        `self` to the precompiled gadget, which may cause unintended behaviors.
        """
        self.compile(rng=rng, force_recompile=force_recompile, execute_actions=False)
        if self.output is None:  # compilation failed
            return None
        return PrecompiledGadget(self.output, self.actions)

    def sanity_check(self) -> bool:
        """Check whether the parameters for the gadget are reasonable.

        The sanity check should be simple, and in particular should not
        depend on other gadgets or compile anything. We also wish to place the
        checks for parameter choices that make no sense at all in __init__().
        The idea is that the sanity check should stop a normal user from using
        incorrect parameters that affect the correctness of the gadget, but can
        be disabled by advanced users if they want to do some weird stuff."""
        return True

    def set_prev_gadget(self, gadget: "Gadget | None") -> None:
        """Set `prev_gadget` to be `gadget`."""
        self.prev_gadget = gadget


class GenericMatch(Gadget):
    """A good ol' match gadget.

    Probably creates a length difference for most compressors out there, but
    may not be able to be chained with other gadgets for non-LZ compressors."""

    def __init__(self, target: bytes):
        super().__init__()
        self.content: bytes = target

    def __bytes__(self) -> bytes:
        return self.content


class PrecompiledGadget(Gadget):
    """A precompiled gadget.

    The output and actions (if any) of the gadget are provided on creation."""

    def __init__(
        self,
        compiled_output: bytes,
        compiled_actions: list[Callable[[Any], None] | None] | None = None,
    ):
        super().__init__()
        self.compiled_output: bytes = compiled_output
        if not compiled_actions:
            compiled_actions = []
        self.compiled_actions: list[Callable[[Compilable], None] | None] = [
            action for action in compiled_actions if action
        ]

        self.output = compiled_output
        self.actions = compiled_actions

    def __call__(self, rng: Random | None = None) -> bytes:
        self.actions = self.compiled_actions
        return self.compiled_output


class RandomGadget(Gadget):
    """A gadget constructed as a random byte string."""

    def __init__(self, length: int, charset: bytes | None = None):
        super().__init__()
        assert length >= 0
        self.length: int = length
        self.charset: bytes | None = charset

    def __call__(self, rng: Random | None) -> bytes:
        charset = charset_with_fallback(self.charset, self.machine)
        return RandBytes(charset, rng).randbytes(self.length)


